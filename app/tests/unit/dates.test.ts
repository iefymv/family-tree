import { describe, expect, test } from 'vitest';
import { dateFields, parseDateText } from '../../src/lib/dates';

describe('parseDateText', () => {
  test.each([
    ['1919', '1919-01-01', '1919-12-31'],
    ['1919 г.', '1919-01-01', '1919-12-31'],
    ['12.03.1955', '1955-03-12', '1955-03-12'],
    ['1.3.1955', '1955-03-01', '1955-03-01'],
    ['1955-03-12', '1955-03-12', '1955-03-12'],
    ['20–25.05.1898', '1898-05-20', '1898-05-25'],
    ['20-25.05.1898', '1898-05-20', '1898-05-25'],
    ['20–25 мая 1919', '1919-05-20', '1919-05-25'],
    ['20 - 25 мая 1919', '1919-05-20', '1919-05-25'],
    ['12 марта 1955', '1955-03-12', '1955-03-12'],
    ['май 1919', '1919-05-01', '1919-05-31'],
    ['Февраль 1900', '1900-02-01', '1900-02-28'],
    ['02.1904', '1904-02-01', '1904-02-29'],
    ['~1902', '1900-01-01', '1904-12-31'],
    ['около 1902', '1900-01-01', '1904-12-31'],
    ['1920-е', '1920-01-01', '1929-12-31'],
    ['1941–1945', '1941-01-01', '1945-12-31'],
    ['1898 (ранее 1891)', '1898-01-01', '1898-12-31'],
    ['  12.03.1955  ', '1955-03-12', '1955-03-12'],
  ])('%s', (text, from, to) => {
    expect(parseDateText(text)).toEqual({ from, to });
  });

  test.each(['', 'весной', '31.02.1950', '25–20.05.1898', '13.13.1950', '1945–1941', 'мартобря 1900', '12/03/1955'])(
    'не понято: %s',
    (text) => expect(parseDateText(text)).toBeNull(),
  );
});

describe('dateFields', () => {
  test('текст сохраняется как написан, диапазон — если понят', () => {
    expect(dateFields(' 20–25 мая 1919 ')).toEqual({ text: '20–25 мая 1919', from: '1919-05-20', to: '1919-05-25' });
    expect(dateFields('весной')).toEqual({ text: 'весной', from: null, to: null });
    expect(dateFields('   ')).toEqual({ text: null, from: null, to: null });
    expect(dateFields(null)).toEqual({ text: null, from: null, to: null });
  });
});
